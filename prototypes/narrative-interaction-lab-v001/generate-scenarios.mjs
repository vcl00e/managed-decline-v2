import { mkdir, writeFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import { SCENARIO_PAYLOAD_GZIP_BASE64 } from "./scenario-payload.mjs";

const decoded = Buffer.from(SCENARIO_PAYLOAD_GZIP_BASE64, "base64");
const variants = JSON.parse(gunzipSync(decoded).toString("utf8"));

await mkdir(new URL("./scenarios/", import.meta.url), { recursive: true });
await writeFile(
  new URL("./scenarios/generated-data.js", import.meta.url),
  `// Generated by generate-scenarios.mjs. Do not edit.\nexport default ${JSON.stringify(variants)};\n`,
  "utf8"
);

console.log("Generated narrative interaction scenario data.");
